/** Khung mới: giữ mọi hàng, chỉ thay những hàng liệt kê. Cùng bề ngang, nên bóng sprite không đổi. */
function pose(rows: readonly string[], edits: Readonly<Record<number, string>>): readonly string[] {
  return rows.map((row, index) => {
    const next = edits[index];
    if (next === undefined) return row;
    if (next.length !== row.length) throw new Error(`khung hình lệch hàng ${index}`);
    return next;
  });
}

